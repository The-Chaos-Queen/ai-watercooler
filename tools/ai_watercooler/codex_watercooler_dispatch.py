def inspect_reviewer_container(policy: Policy, name: str) -> str | None:
    if re.fullmatch(r"codex-wc-[1-9][0-9]*-[1-9][0-9]*", name) is None:
        raise DispatchError("refusing to inspect a malformed reviewer container name")
    inspected = _run_wsl_docker(
        policy,
        ["container", "inspect", "--format", "{{.State.Status}}", name],
        timeout=30,
    )
    if inspected.returncode == 0:
        status = inspected.stdout.strip()
        if status not in {"created", "running", "paused", "restarting", "removing", "exited", "dead"}:
            raise DispatchError("Docker returned an unsupported reviewer container state")
        return status
    if "No such object" in inspected.stderr or "No such container" in inspected.stderr:
        return None
    raise DispatchError("could not inspect the isolated reviewer container")


