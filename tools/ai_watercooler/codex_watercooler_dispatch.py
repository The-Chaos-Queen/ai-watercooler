def windows_path_to_wsl(path: Path) -> str:
    resolved = str(path.expanduser().resolve())
    matched = re.fullmatch(r"([A-Za-z]):[\\/](.*)", resolved)
    if matched is not None:
        drive = matched.group(1).casefold()
        suffix = matched.group(2).replace("\\", "/")
        return f"/mnt/{drive}/{suffix}"
    if resolved.startswith("/"):  # pragma: no cover - portable unit use
        return resolved
    raise DispatchError(f"path is not mountable through WSL: {resolved}")


